/** 液相线（B 级物理公式，企业「材料标准」）：TL = 1650 − 124.5C − 26.7Si − 65.4P（成分 wt%） */
export function liquidus(C, Si, P) {
  return 1650 - 124.5 * C - 26.7 * Si - 65.4 * P;
}
