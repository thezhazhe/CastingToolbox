// ⑤ 通用（什么都不选）
export const GENERAL_YIELD = [40, 60];

/** 多级回退解析：返回 { range, basis, level } */
export function resolveYield(matKey, product, process) {
  if (product && process && PRODUCT_YIELD[product]?.[process]) {
    return { range: PRODUCT_YIELD[product][process], basis: `「${product}」×「${process}」`, level: 1 };
  }
  if (matKey && process && MAT_PROCESS_YIELD[matKey]?.[process]) {
    return { range: MAT_PROCESS_YIELD[matKey][process], basis: `「${matKey}」×「${process}」`, level: 2 };
  }
  if (process && PROCESS_YIELD[process]) {
    return { range: PROCESS_YIELD[process], basis: `「${process}」`, level: 3 };
  }
  if (matKey && MATERIALS[matKey]) {
    const md = MATERIALS[matKey];
    return { range: [md.y_min, md.y_max], basis: `「${matKey}」`, level: 4 };
  }
  return { range: GENERAL_YIELD, basis: '通用参考', level: 5 };
}
